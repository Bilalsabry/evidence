//! Span-picker. Given a PDF, render a TOML-friendly listing of every
//! span on every page (or a filtered page range), then emit a skeleton
//! `[[example]]` block with placeholders.
//!
//! The output is designed to be edited in-place: the author picks 2-5
//! spans from the comment block at the top, pastes them into the
//! skeleton's `corpus_spans`, fills in the question / sentence / class,
//! and runs `evidence-eval lint` to catch authoring mistakes before
//! `evidence-eval run`.
//!
//! Span IDs are `page_num * 1000 + idx * 10`, so page 1 spans start at
//! 1000, page 2 at 2000, etc. The `*10` stride leaves gaps for editing,
//! and the per-page base keeps IDs visually grouped by page.
//!
//! No DB. No ingest persistence. Self-contained authoring loop against
//! a PDF on disk.

use std::fmt::Write as _;
use std::path::Path;

use evidence_core::ingest::pdf::{self, Page, PdfError};

/// Render options for [`render_template`].
#[derive(Debug, Clone)]
pub struct AuthorOptions {
    /// If `Some`, only print spans on this page. `None` → all pages.
    pub page: Option<u32>,
    /// Suggested example name to drop into the skeleton's `name` field.
    pub name: String,
    /// Suggested example class. Defaults to "valid"; the author can
    /// flip to any other class as needed.
    pub class: String,
    /// Optional cap on span text length for the comment block, to keep
    /// each comment line tractable. Defaults to 240.
    pub text_truncate: usize,
}

impl Default for AuthorOptions {
    fn default() -> Self {
        Self {
            page: None,
            name: "FILL_IN_AUTHOR_NAME".to_string(),
            class: "valid".to_string(),
            text_truncate: 240,
        }
    }
}

/// Errors surfaced by the author command.
#[derive(Debug, thiserror::Error)]
pub enum AuthorError {
    #[error("PDF extraction failed: {0}")]
    Pdf(#[from] PdfError),
}

/// Generate a TOML authoring template from a PDF on disk.
///
/// # Errors
///
/// Returns [`AuthorError::Pdf`] if the PDF can't be parsed.
pub fn render_for_pdf<P: AsRef<Path>>(
    path: P,
    options: &AuthorOptions,
) -> Result<String, AuthorError> {
    let pages = pdf::extract(path)?;
    Ok(render_template(&pages, options))
}

/// Render the template against already-parsed pages. Split out from
/// `render_for_pdf` for tests that don't want to hit PDFium.
#[must_use]
pub fn render_template(pages: &[Page], options: &AuthorOptions) -> String {
    let mut out = String::new();

    let _ = writeln!(out, "# Auto-generated by `evidence-eval author`.");
    let _ = writeln!(
        out,
        "# Trim the comment block to 2–5 spans, paste into corpus_spans,"
    );
    let _ = writeln!(
        out,
        "# fill in prompt_chunks + response_sentences, then run:"
    );
    let _ = writeln!(out, "#     evidence-eval lint <this-file>");
    out.push('\n');

    let _ = writeln!(
        out,
        "# === Spans extracted from the PDF (id, page, text) ==="
    );
    for page in pages {
        if let Some(filter) = options.page {
            if page.page_num != filter {
                continue;
            }
        }
        for (idx, span) in page.spans.iter().enumerate() {
            let span_id = id_for(page.page_num, idx);
            let text = truncate(&span.text, options.text_truncate);
            let _ = writeln!(
                out,
                "#   {{ id = {span_id}, page = {page_num}, text = {text} }},",
                page_num = page.page_num,
                text = toml_string(&text),
            );
        }
    }
    out.push('\n');

    let _ = writeln!(out, "[[example]]");
    let _ = writeln!(out, "name = {}", toml_string(&options.name));
    let _ = writeln!(out, "class = {}", toml_string(&options.class));
    let _ = writeln!(out, "description = \"\"");
    out.push('\n');

    let _ = writeln!(
        out,
        "# Paste 1–5 spans from the comment block above into the next list."
    );
    let _ = writeln!(
        out,
        "# Re-number the ids if you like — they're author-assigned."
    );
    let _ = writeln!(out, "corpus_spans = [");
    let _ = writeln!(out, "    # {{ id = 10, page = 1, text = \"…\" }},");
    let _ = writeln!(out, "]");
    out.push('\n');

    let _ = writeln!(
        out,
        "# Declare which spans the model was \"shown\" for this question."
    );
    let _ = writeln!(out, "prompt_chunks = [");
    let _ = writeln!(
        out,
        "    # {{ id = 1, span_range = [LOW, HIGH], text = \"…concat the corpus span text…\" }},"
    );
    let _ = writeln!(out, "]");
    out.push('\n');

    let _ = writeln!(
        out,
        "# The model's fixture response. cited_spans = [] for class=uncited."
    );
    let _ = writeln!(out, "response_sentences = [");
    let _ = writeln!(
        out,
        "    # {{ text = \"FILL_IN_ANSWER\", cited_spans = [SPAN_ID] }},"
    );
    let _ = writeln!(out, "]");
    out.push('\n');

    let _ = writeln!(
        out,
        "# For class=valid only: list contrast-set mutations the injection harness"
    );
    let _ = writeln!(
        out,
        "# will materialize as derived `unsupported`/`contradicted` examples."
    );
    let _ = writeln!(out, "# [[example.support_mutations]]");
    let _ = writeln!(out, "# text = \"…rewrite that flips the claim…\"");
    let _ = writeln!(out, "# class = \"contradicted\"");

    out
}

/// Assign a stable span ID per page. Uses page_num * 1000 + idx * 10 so
/// different pages get distinct ID ranges and there's room between IDs
/// for inserts.
fn id_for(page_num: u32, idx: usize) -> i64 {
    i64::from(page_num) * 1000 + i64::try_from(idx).unwrap_or(0) * 10
}

/// Truncate `s` to `max` chars with an ellipsis if cut.
fn truncate(s: &str, max: usize) -> String {
    if s.chars().count() <= max {
        s.to_string()
    } else {
        let cut: String = s.chars().take(max).collect();
        format!("{cut}…")
    }
}

/// Quote a string as a TOML basic-string literal. Escapes `"` and `\`;
/// keeps newlines as `\n` so each comment line stays single-line.
fn toml_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use evidence_core::ingest::pdf::{Bbox, Span};

    fn fake_page(page_num: u32, texts: &[&str]) -> Page {
        let mut spans = Vec::with_capacity(texts.len());
        let mut offset = 0;
        let mut raw_text = String::new();
        for text in texts {
            let start = offset;
            let end = offset + text.len();
            spans.push(Span {
                start_offset: start,
                end_offset: end,
                text: (*text).to_string(),
                bbox: Bbox {
                    x0: 0.0,
                    y0: 0.0,
                    x1: 0.0,
                    y1: 0.0,
                },
            });
            raw_text.push_str(text);
            offset = end;
        }
        Page {
            page_num,
            raw_text,
            spans,
        }
    }

    #[test]
    fn template_lists_every_span_when_no_page_filter() {
        let pages = vec![fake_page(1, &["alpha", "beta"]), fake_page(2, &["gamma"])];
        let out = render_template(&pages, &AuthorOptions::default());
        assert!(out.contains(r#"text = "alpha""#));
        assert!(out.contains(r#"text = "beta""#));
        assert!(out.contains(r#"text = "gamma""#));
    }

    #[test]
    fn template_respects_page_filter() {
        let pages = vec![fake_page(1, &["alpha"]), fake_page(2, &["beta"])];
        let opts = AuthorOptions {
            page: Some(2),
            ..AuthorOptions::default()
        };
        let out = render_template(&pages, &opts);
        assert!(!out.contains(r#"text = "alpha""#));
        assert!(out.contains(r#"text = "beta""#));
    }

    #[test]
    fn template_uses_author_supplied_name_and_class() {
        let pages = vec![fake_page(1, &["x"])];
        let opts = AuthorOptions {
            name: "valid_dose_titration".to_string(),
            class: "contradicted".to_string(),
            ..AuthorOptions::default()
        };
        let out = render_template(&pages, &opts);
        assert!(out.contains(r#"name = "valid_dose_titration""#));
        assert!(out.contains(r#"class = "contradicted""#));
    }

    #[test]
    fn span_ids_are_per_page_distinct() {
        let pages = vec![fake_page(1, &["a", "b"]), fake_page(2, &["c"])];
        let out = render_template(&pages, &AuthorOptions::default());
        // page 1 → ids 1000, 1010
        assert!(out.contains("id = 1000"));
        assert!(out.contains("id = 1010"));
        // page 2 → id 2000
        assert!(out.contains("id = 2000"));
    }

    #[test]
    fn long_text_is_truncated() {
        let long_text = "x".repeat(500);
        let pages = vec![fake_page(1, &[&long_text])];
        let opts = AuthorOptions {
            text_truncate: 50,
            ..AuthorOptions::default()
        };
        let out = render_template(&pages, &opts);
        // The 51st character should be an ellipsis, not an 'x'.
        let line = out
            .lines()
            .find(|l| l.contains("id = 1000"))
            .expect("span line");
        assert!(line.contains("…"));
    }

    #[test]
    fn toml_string_escapes_quotes_and_backslashes() {
        assert_eq!(toml_string(r#"a"b"#), r#""a\"b""#);
        assert_eq!(toml_string(r"a\b"), r#""a\\b""#);
        assert_eq!(toml_string("a\nb"), r#""a\nb""#);
    }

    #[test]
    fn template_includes_skeleton_blocks() {
        let pages = vec![fake_page(1, &["x"])];
        let out = render_template(&pages, &AuthorOptions::default());
        assert!(out.contains("[[example]]"));
        assert!(out.contains("corpus_spans"));
        assert!(out.contains("prompt_chunks"));
        assert!(out.contains("response_sentences"));
        assert!(out.contains("support_mutations"));
    }
}
