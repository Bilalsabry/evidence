//! Failure-injection operators for matched-pair contrast-set generation.
//!
//! For each `valid` example in a dataset, three operators derive
//! labeled failure variants:
//!
//! - [`inject_existence`] swaps the citation to a span ID that
//!   doesn't exist in the corpus. The validator's gate 1 catches it.
//! - [`inject_in_context`] adds a duplicate-text span at a fresh ID
//!   that is *not* in the prompt's chunk set, then rewrites the
//!   citation to point at it. Gate 1 passes (the span exists); gate
//!   2 catches it.
//! - [`inject_support`] applies an author-supplied
//!   [`SupportMutation`](crate::dataset::SupportMutation) to the
//!   sentence text. The citation is unchanged; the *claim* the
//!   citation backs is rewritten. Gates 1 and 2 pass; gate 3 catches
//!   it (when the NLI model agrees with the mutation's labeled class).
//!
//! These operators implement the contrast-set methodology of
//! Gardner et al. 2020: each injected failure is generated by a
//! specific named operator applied to a known-good seed. Pairs are
//! "matched" — they share corpus and prompt with the parent — which
//! is what lets the paper measure each gate's contribution in
//! isolation.

use crate::dataset::{CorpusSpan, Example, HallucinationClass, SupportMutation};

/// Tunables for the injection operators.
#[derive(Debug, Clone)]
pub struct InjectionConfig {
    /// Page number used for the duplicate span generated by
    /// [`inject_in_context`]. Picking a high number avoids collisions
    /// with seed corpora that use page 1..N for the prompt chunks.
    pub fresh_page: u32,
    /// Offset added to the parent's maximum span ID when generating a
    /// fresh ID. Picking a non-adjacent value avoids confusion with
    /// `fabricated_span_off_by_one`-style examples.
    pub fresh_id_offset: i64,
}

impl Default for InjectionConfig {
    fn default() -> Self {
        Self {
            fresh_page: 1000,
            fresh_id_offset: 10_000,
        }
    }
}

/// Errors from the injection operators.
#[derive(Debug, thiserror::Error)]
pub enum InjectionError {
    #[error("only `valid` examples can be injected; '{name}' has class {class:?}")]
    NotValidSeed {
        name: String,
        class: HallucinationClass,
    },
    #[error("'{name}' has no response sentences to mutate")]
    EmptyResponse { name: String },
    #[error("support mutation has invalid class {class:?}; must be Unsupported or Contradicted")]
    BadSupportMutationClass { class: HallucinationClass },
}

/// Generate every available injection variant from one valid example.
/// Returns existence + in-context + one variant per `support_mutations`
/// entry. An example with no support_mutations yields two variants.
///
/// # Errors
///
/// Returns [`InjectionError::NotValidSeed`] if the parent isn't valid,
/// [`InjectionError::EmptyResponse`] if it has no sentences, or
/// [`InjectionError::BadSupportMutationClass`] if any mutation names a
/// class other than `Unsupported` or `Contradicted`.
pub fn inject_all_variants(
    parent: &Example,
    config: &InjectionConfig,
) -> Result<Vec<Example>, InjectionError> {
    require_valid_seed(parent)?;
    let mut out = Vec::with_capacity(2 + parent.support_mutations.len());
    out.push(inject_existence(parent, config)?);
    out.push(inject_in_context(parent, config)?);
    for (idx, mutation) in parent.support_mutations.iter().enumerate() {
        out.push(inject_support(parent, mutation, idx)?);
    }
    Ok(out)
}

/// Rewrite the first sentence's first citation to a span ID
/// guaranteed not to exist in the corpus. Class flips to
/// `FabricatedSpan`.
///
/// # Errors
///
/// See [`inject_all_variants`].
pub fn inject_existence(
    parent: &Example,
    config: &InjectionConfig,
) -> Result<Example, InjectionError> {
    require_valid_seed(parent)?;
    if parent.response_sentences.is_empty() {
        return Err(InjectionError::EmptyResponse {
            name: parent.name.clone(),
        });
    }
    let fresh_id = fresh_span_id(parent, config);
    let mut response = parent.response_sentences.clone();
    // Replace the *first* cited span on the first sentence. The rest of
    // the response shape stays identical to the parent.
    if let Some(first_cite) = response[0].cited_spans.get_mut(0) {
        *first_cite = fresh_id;
    } else {
        response[0].cited_spans = vec![fresh_id];
    }
    Ok(Example {
        name: format!("{}__inject_existence", parent.name),
        class: HallucinationClass::FabricatedSpan,
        description: format!(
            "Injection from {}: citation rewritten to a span ID not in the corpus.",
            parent.name
        ),
        corpus_spans: parent.corpus_spans.clone(),
        prompt_chunks: parent.prompt_chunks.clone(),
        response_sentences: response,
        support_mutations: Vec::new(),
    })
}

/// Add a fresh span to the corpus (on a page outside any prompt chunk)
/// whose text duplicates the cited-span content, then rewrite the first
/// citation to point at it. Gate 1 passes (the new span exists); gate 2
/// rejects it (it wasn't in the prompt's allowed range). Class flips to
/// `OutOfContext`.
///
/// # Errors
///
/// See [`inject_all_variants`].
pub fn inject_in_context(
    parent: &Example,
    config: &InjectionConfig,
) -> Result<Example, InjectionError> {
    require_valid_seed(parent)?;
    if parent.response_sentences.is_empty() {
        return Err(InjectionError::EmptyResponse {
            name: parent.name.clone(),
        });
    }
    let fresh_id = fresh_span_id(parent, config);

    // Duplicate the *first cited span's* text into a new corpus span.
    // We pick the duplicate so the validator can't claim "you cited
    // something irrelevant" — the failure mode is purely "you cited a
    // span we didn't show you."
    let dup_text = parent
        .response_sentences
        .first()
        .and_then(|s| s.cited_spans.first())
        .and_then(|cite| {
            parent
                .corpus_spans
                .iter()
                .find(|c| c.id == *cite)
                .map(|c| c.text.clone())
        })
        .unwrap_or_else(|| "[injected duplicate for in-context test]".to_string());

    let mut corpus = parent.corpus_spans.clone();
    corpus.push(CorpusSpan {
        id: fresh_id,
        page: config.fresh_page,
        text: dup_text,
    });

    let mut response = parent.response_sentences.clone();
    if let Some(first_cite) = response[0].cited_spans.get_mut(0) {
        *first_cite = fresh_id;
    } else {
        response[0].cited_spans = vec![fresh_id];
    }

    Ok(Example {
        name: format!("{}__inject_in_context", parent.name),
        class: HallucinationClass::OutOfContext,
        description: format!(
            "Injection from {}: citation rewritten to a fresh corpus span outside the prompt's chunk set.",
            parent.name
        ),
        corpus_spans: corpus,
        prompt_chunks: parent.prompt_chunks.clone(),
        response_sentences: response,
        support_mutations: Vec::new(),
    })
}

/// Apply an author-supplied [`SupportMutation`] to the first sentence's
/// text. Citations are unchanged; the *claim* is rewritten. Gates 1 and
/// 2 pass; gate 3 catches the mismatch (when the NLI model agrees with
/// the labeled class).
///
/// `mutation_idx` is used only for naming the derived example.
///
/// # Errors
///
/// See [`inject_all_variants`].
pub fn inject_support(
    parent: &Example,
    mutation: &SupportMutation,
    mutation_idx: usize,
) -> Result<Example, InjectionError> {
    require_valid_seed(parent)?;
    if parent.response_sentences.is_empty() {
        return Err(InjectionError::EmptyResponse {
            name: parent.name.clone(),
        });
    }
    if !matches!(
        mutation.class,
        HallucinationClass::Unsupported | HallucinationClass::Contradicted
    ) {
        return Err(InjectionError::BadSupportMutationClass {
            class: mutation.class,
        });
    }

    let mut response = parent.response_sentences.clone();
    response[0].text = mutation.text.clone();

    let suffix = match mutation.class {
        HallucinationClass::Unsupported => "unsupported",
        HallucinationClass::Contradicted => "contradicted",
        _ => unreachable!("validated above"),
    };

    Ok(Example {
        name: format!(
            "{}__inject_support_{}_{}",
            parent.name, suffix, mutation_idx
        ),
        class: mutation.class,
        description: format!(
            "Injection from {}: sentence text rewritten to {} the cited span.",
            parent.name,
            match mutation.class {
                HallucinationClass::Unsupported => "be off-topic for",
                HallucinationClass::Contradicted => "contradict",
                _ => unreachable!(),
            }
        ),
        corpus_spans: parent.corpus_spans.clone(),
        prompt_chunks: parent.prompt_chunks.clone(),
        response_sentences: response,
        support_mutations: Vec::new(),
    })
}

fn require_valid_seed(parent: &Example) -> Result<(), InjectionError> {
    if parent.class != HallucinationClass::Valid {
        return Err(InjectionError::NotValidSeed {
            name: parent.name.clone(),
            class: parent.class,
        });
    }
    Ok(())
}

fn fresh_span_id(parent: &Example, config: &InjectionConfig) -> i64 {
    let max_id = parent
        .corpus_spans
        .iter()
        .map(|s| s.id)
        .max()
        .unwrap_or(0)
        .max(
            parent
                .prompt_chunks
                .iter()
                .flat_map(|c| [c.span_range[0], c.span_range[1]])
                .max()
                .unwrap_or(0),
        );
    max_id.saturating_add(config.fresh_id_offset)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dataset::{PromptChunk, ResponseSentence};

    fn valid_seed() -> Example {
        Example {
            name: "valid_dose".to_string(),
            class: HallucinationClass::Valid,
            description: String::new(),
            corpus_spans: vec![CorpusSpan {
                id: 100,
                page: 1,
                text: "Pembrolizumab at 200 mg every 21 days.".to_string(),
            }],
            prompt_chunks: vec![PromptChunk {
                id: 1,
                span_range: [100, 100],
                text: "Pembrolizumab at 200 mg every 21 days.".to_string(),
            }],
            response_sentences: vec![ResponseSentence {
                text: "Pembrolizumab at 200 mg every 21 days.".to_string(),
                cited_spans: vec![100],
            }],
            support_mutations: vec![SupportMutation {
                text: "Pembrolizumab at 400 mg every 21 days.".to_string(),
                class: HallucinationClass::Contradicted,
            }],
        }
    }

    #[test]
    fn existence_swaps_to_fresh_id() {
        let parent = valid_seed();
        let child = inject_existence(&parent, &InjectionConfig::default()).unwrap();
        assert_eq!(child.class, HallucinationClass::FabricatedSpan);
        assert_eq!(child.name, "valid_dose__inject_existence");
        assert_ne!(child.response_sentences[0].cited_spans[0], 100);
        // The fresh ID must not appear in the corpus.
        let fresh = child.response_sentences[0].cited_spans[0];
        assert!(child.corpus_spans.iter().all(|s| s.id != fresh));
    }

    #[test]
    fn in_context_adds_a_corpus_span_outside_the_prompt() {
        let parent = valid_seed();
        let child = inject_in_context(&parent, &InjectionConfig::default()).unwrap();
        assert_eq!(child.class, HallucinationClass::OutOfContext);
        assert_eq!(child.corpus_spans.len(), parent.corpus_spans.len() + 1);
        let fresh = child.response_sentences[0].cited_spans[0];
        // Fresh ID exists in the corpus...
        assert!(child.corpus_spans.iter().any(|s| s.id == fresh));
        // ...but isn't inside any prompt_chunk's span_range.
        let in_prompt = child
            .prompt_chunks
            .iter()
            .any(|c| c.span_range[0] <= fresh && fresh <= c.span_range[1]);
        assert!(!in_prompt);
    }

    #[test]
    fn support_uses_author_supplied_text() {
        let parent = valid_seed();
        let mutation = &parent.support_mutations[0];
        let child = inject_support(&parent, mutation, 0).unwrap();
        assert_eq!(child.class, HallucinationClass::Contradicted);
        assert_eq!(child.response_sentences[0].text, mutation.text);
        // Citations are preserved from parent.
        assert_eq!(child.response_sentences[0].cited_spans, vec![100]);
    }

    #[test]
    fn support_rejects_invalid_class() {
        let parent = valid_seed();
        let bad = SupportMutation {
            text: "x".to_string(),
            class: HallucinationClass::FabricatedSpan, // not allowed
        };
        assert!(matches!(
            inject_support(&parent, &bad, 0),
            Err(InjectionError::BadSupportMutationClass { .. })
        ));
    }

    #[test]
    fn cannot_inject_a_non_valid_seed() {
        let mut parent = valid_seed();
        parent.class = HallucinationClass::FabricatedSpan;
        assert!(matches!(
            inject_existence(&parent, &InjectionConfig::default()),
            Err(InjectionError::NotValidSeed { .. })
        ));
    }

    #[test]
    fn inject_all_variants_emits_two_plus_one_per_mutation() {
        let parent = valid_seed();
        let variants = inject_all_variants(&parent, &InjectionConfig::default()).unwrap();
        assert_eq!(variants.len(), 3); // existence + in_context + 1 support_mutation
    }
}
